def _privileges(db, table: str) -> dict[str, bool]:
    return {
        right: db.execute(
            "SELECT has_table_privilege('app_rw', %s, %s)", (table, right)
        ).fetchone()[0]
        for right in ("SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE")
    }


@pytest.mark.parametrize("table", ["ti_ioc", "ti_import_log"])
def test_app_rw_reads_inserts_and_updates_and_nothing_more(db, table):
    assert _privileges(db, table) == {
        "SELECT": True,
        "INSERT": True,
        "UPDATE": True,
        "DELETE": False,
        "TRUNCATE": False,
    }


def test_app_rw_really_does_what_the_grants_say(db):
    """The real role, not the catalog: it inserts (the identity column makes the id with no sequence right,
    which is taken away first so the proof does not lean on a default privilege), upserts, updates, and is
    refused DELETE and TRUNCATE on both tables."""
    db.execute("SELECT 1")  # open the fixture's outer transaction: the blocks below are savepoints
    with db.transaction(force_rollback=True):
        for table in ("ti_ioc", "ti_import_log"):
            sequence = db.execute("SELECT pg_get_serial_sequence(%s, 'id')", (table,)).fetchone()[0]
            assert sequence, f"{table}.id has no sequence behind it"
            db.execute(
                sql.SQL("REVOKE ALL ON SEQUENCE {} FROM app_rw").format(
                    sql.Identifier(*sequence.split("."))
                )
            )
            assert db.execute(
                "SELECT has_sequence_privilege('app_rw', %s, 'USAGE')", (sequence,)
            ).fetchone() == (False,)
        db.execute("SET LOCAL ROLE app_rw")

        ioc_id = _ioc(db)
        db.execute("UPDATE ti_ioc SET malware = 'x' WHERE id = %s", (ioc_id,))
        assert db.execute("SELECT malware FROM ti_ioc WHERE id = %s", (ioc_id,)).fetchone() == (
            "x",
        )
        upserted = db.execute(
            "INSERT INTO ti_ioc (source, type, value, first_seen, last_seen, imported_at, expires_at) "
            "SELECT source, type, value, first_seen, last_seen, imported_at, expires_at "
            "FROM ti_ioc WHERE id = %s "
            "ON CONFLICT ON CONSTRAINT uq_ti_ioc_key DO UPDATE SET last_seen = EXCLUDED.last_seen "
            "RETURNING id",
            (ioc_id,),
        ).fetchone()
        assert upserted == (ioc_id,)

        log_id = _log(db)
        db.execute("UPDATE ti_import_log SET message = 'x' WHERE id = %s", (log_id,))
        assert db.execute(
            "SELECT message FROM ti_import_log WHERE id = %s", (log_id,)
        ).fetchone() == ("x",)

        for table, row_id in (("ti_ioc", ioc_id), ("ti_import_log", log_id)):
            for statement in (f"DELETE FROM {table} WHERE id = %s", f"TRUNCATE {table}"):
                with (
                    db.transaction(force_rollback=True),
                    pytest.raises(psycopg.errors.InsufficientPrivilege),
                ):
                    db.execute(statement, (row_id,) if "%s" in statement else None)


# ── upgrade, the way `make migrate` runs it ─────────────────────────────────────────────────


def _tree_plus_026(tree: Path, tmp_path: Path) -> Path:
    with_026 = tmp_path / f"{tree.name}_plus_026"
    shutil.copytree(tree, with_026)
    shutil.copy(MIGRATION_FILE, with_026)
    return with_026


def _relations(conn) -> set[str]:
    """Every table, sequence and index of the public schema, by name."""
    return {
        name
        for (name,) in conn.execute(
            "SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace "
            "WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'S', 'i', 'v', 'm')"
        )
    }


def _catalog(conn, tables: set[str]) -> dict:
    """The shape of `tables`, whole: columns, constraints, indexes, triggers and rights. Compared before
    and after 026 on the tables that were there before."""
    names = sorted(tables)
    queries = {
        "columns": (
            "SELECT c.relname, a.attnum, a.attname, format_type(a.atttypid, a.atttypmod), "
            "a.attnotnull, a.attidentity, pg_get_expr(d.adbin, d.adrelid) "
            "FROM pg_class c JOIN pg_attribute a ON a.attrelid = c.oid "
            "LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum "
            "WHERE c.relname = ANY(%s) AND c.relkind IN ('r', 'p') AND a.attnum > 0 "
            "AND NOT a.attisdropped ORDER BY 1, 2"
        ),
        "constraints": (
            "SELECT conrelid::regclass::text, conname, pg_get_constraintdef(oid) FROM pg_constraint "
            "WHERE conrelid::regclass::text = ANY(%s) ORDER BY 1, 2"
        ),
        "indexes": (
            "SELECT tablename, indexname, indexdef FROM pg_indexes "
            "WHERE schemaname = 'public' AND tablename = ANY(%s) ORDER BY 1, 2"
        ),
        "triggers": (
            "SELECT tgrelid::regclass::text, tgname, pg_get_triggerdef(oid) FROM pg_trigger "
            "WHERE NOT tgisinternal AND tgrelid::regclass::text = ANY(%s) ORDER BY 1, 2"
        ),
        "rights": (
            "SELECT table_name, grantee, privilege_type FROM information_schema.table_privileges "
            "WHERE table_schema = 'public' AND table_name = ANY(%s) ORDER BY 1, 2, 3"
        ),
    }
    shot = {key: conn.execute(query, (names,)).fetchall() for key, query in queries.items()}
    shot["functions"] = conn.execute(
        "SELECT proname FROM pg_proc WHERE pronamespace = 'public'::regnamespace ORDER BY 1"
    ).fetchall()
    return shot


def test_026_applies_on_a_database_below_it_the_way_make_migrate_runs_it(tmp_path):
    """The live database is below 026: `make migrate` applies the 026 FILE to it, never `schema.sql`. The
    shared fixture builds from `schema.sql`, so on its own it would not notice a 026 that differs from what
    `schema.sql` holds. A database is built from the tree below 026, then the real `migrate.sh` applies the
    real file, and a third run shows `schema_migrations` refuses a second apply."""
    if shutil.which("psql") is None:
        pytest.skip("psql is not installed")
    below = _schema_tree_through(25, tmp_path)
    with_026 = _tree_plus_026(below, tmp_path)
    before = len(list(below.glob(MIGRATION_FILES)))
    assert not list(below.glob("026_*.sql")) and before == 25
    assert len(list(with_026.glob(MIGRATION_FILES))) == before + 1

    admin, dbname, dsn = _scratch("026up")
    try:
        runs = [_migrate(dsn, mig_dir) for mig_dir in (below, with_026, with_026)]
        assert "026_threat_intel" not in runs[0]
        assert f"migrate: 0 applied, {before} already present" in runs[0]
        assert "migrate: applying 026_threat_intel" in runs[1]
        assert f"migrate: 1 applied, {before} already present" in runs[1]
        assert f"migrate: 0 applied, {before + 1} already present" in runs[2]
        assert "migrate: applying" not in runs[2]
        with psycopg.connect(dsn) as conn:
            recorded = {r[0] for r in conn.execute("SELECT version FROM schema_migrations")}
            assert recorded == {p.stem for p in with_026.glob(MIGRATION_FILES)}
            names = _quoted(_constraint_def(conn, "audit_events", "ck_audit_event_type"))
            assert names == EVENTS_BEFORE_025 + EVENTS_IN_025
            _ioc(conn, value="mig26-up.example.com")
            _log(conn)
            assert conn.execute("SELECT count(*) FROM ti_ioc").fetchone() == (1,)
            assert conn.execute("SELECT count(*) FROM ti_import_log").fetchone() == (1,)
            conn.rollback()
    finally:
        admin.execute(sql.SQL("DROP DATABASE IF EXISTS {}").format(sql.Identifier(dbname)))
        admin.close()


def test_026_adds_two_tables_with_their_keys_and_indexes_and_changes_nothing_else(tmp_path):
    """A database at 025 holds a user, alerts and an audit row of every one of the 42 names; it takes 026.
    Every relation 026 adds is one of the twelve it names; every old table keeps its columns, constraints,
    indexes, triggers and rights; every old row is as it was; the new tables are empty."""
    if shutil.which("psql") is None:
        pytest.skip("psql is not installed")
    below = _schema_tree_through(25, tmp_path)
    with_026 = _tree_plus_026(below, tmp_path)
    admin, dbname, dsn = _scratch("026seed")
    try:
        assert "migrate: applying 026_threat_intel" not in _migrate(dsn, below)
        with psycopg.connect(dsn) as conn:
            insert_user(conn, "admin")
            for i in range(3):
                insert_alert(conn, f"mig26-seed-{i}")
            for name in EVENTS_BEFORE_025 + EVENTS_IN_025:
                conn.execute(
                    "INSERT INTO audit_events (event_type, subject_id, actor_role) "
                    "VALUES (%s, %s, 'system')",
                    (name, f"seed-{name}"),
                )
            conn.commit()
            relations_before = _relations(conn)
            tables_before = {
                name
                for (name,) in conn.execute(
                    "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
                )
            }
            catalog_before = _catalog(conn, tables_before)
        seeded = _everything(dsn)
        assert len(seeded["audit_events"]) >= 42 and len(seeded["alerts"]) == 3

        applied = _migrate(dsn, with_026)

        assert "migrate: applying 026_threat_intel" in applied
        assert _everything(dsn) == seeded
        with psycopg.connect(dsn) as conn:
            assert _relations(conn) - relations_before == NEW_RELATIONS
            assert relations_before - _relations(conn) == set()
            assert _catalog(conn, tables_before) == catalog_before
            assert conn.execute("SELECT count(*) FROM ti_ioc").fetchone() == (0,)
            assert conn.execute("SELECT count(*) FROM ti_import_log").fetchone() == (0,)
    finally:
        admin.execute(sql.SQL("DROP DATABASE IF EXISTS {}").format(sql.Identifier(dbname)))
        admin.close()
